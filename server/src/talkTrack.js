// The SE talk track is data (data/talk-track.json). docs/talk-track.md is generated from it by scripts/build-talk-track.mjs, and a test
// fails when the file differs from what this renders, so the doc cannot drift from the data.
import fs from 'node:fs';
import { SCENARIOS } from './stories.js';

export const TALK_TRACK = JSON.parse(fs.readFileSync(new URL('../data/talk-track.json', import.meta.url), 'utf8'));

// Every story id named in the flow must be a real scenario. Returns the unknown ids.
export function unknownStories(data = TALK_TRACK) {
  const ids = new Set(SCENARIOS.map((s) => s.id));
  return data.flow.flatMap((f) => f.stories).filter((id) => !ids.has(id));
}

// "S17 S18 S19" reads badly aloud. Runs of three or more consecutive ids become "S17 to S19"; everything else is comma-separated.
export function formatStories(ids) {
  const out = [];
  for (let i = 0; i < ids.length;) {
    const m = /^([A-Za-z]+)(\d+)$/.exec(ids[i]);
    let j = i;
    while (m && j + 1 < ids.length) {
      const n = /^([A-Za-z]+)(\d+)$/.exec(ids[j + 1]);
      if (n && n[1] === m[1] && Number(n[2]) === Number(/^[A-Za-z]+(\d+)$/.exec(ids[j])[1]) + 1) j++; else break;
    }
    if (j - i >= 2) { out.push(`${ids[i]} to ${ids[j]}`); i = j + 1; } else { out.push(ids[i]); i++; }
  }
  return out.join(', ');
}

export function renderTalkTrackMarkdown(data = TALK_TRACK) {
  const lines = [`# ${data.title}`, '', '<!-- Generated by scripts/build-talk-track.mjs from server/data/talk-track.json. Edit the data, then run npm run talk-track. -->', '', data.intro, '', '## The one-sentence point', '', `"${data.point}"`, '', '## Flow', ''];
  data.flow.forEach((f, i) => lines.push(`${i + 1}. **${f.title}${f.stories.length ? `, ${formatStories(f.stories)}` : ''} (${f.time}).** ${f.say}`));
  lines.push('', '## Likely questions', '');
  for (const q of data.questions) lines.push(`- **"${q.q}"** ${q.a}`);
  lines.push('', '## If something goes wrong', '', data.trouble, '');
  return lines.join('\n');
}
